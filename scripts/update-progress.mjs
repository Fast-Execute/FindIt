// Recalculates FindIt progress from docs/ROADMAP.md.
// Usage: node scripts/update-progress.mjs
import { readFileSync, writeFileSync } from "node:fs";

const roadmap = readFileSync("docs/ROADMAP.md", "utf8");
const lines = roadmap.split("\n");

const done = lines.filter((l) => /^- \[x\] /.test(l)).length;
const open = lines.filter((l) => /^- \[ \] /.test(l));
const total = done + open.length;
const percent = Math.round((done / total) * 100);

const WIDTH = 38;
const filled = Math.round((percent / 100) * WIDTH);
const bar = `[${"█".repeat(filled)}${"░".repeat(WIDTH - filled)}] ${percent}%`;
const headline = `**Overall progress (roadmap): ${percent}%** (${done} of ${total} tasks)`;

// README: replace the headline and the bar block.
let readme = readFileSync("README.md", "utf8");
readme = readme
  .replace(/\*\*Overall progress[^\n]*\*\*[^\n]*/, headline)
  .replace(/\[[█░]+\] \d+%/, bar);
writeFileSync("README.md", readme);

// PROGRESS.md: regenerated from the roadmap.
const next = open.slice(0, 8).map((l) => l.replace("- [ ] ", "- [ ] "));
const progress = `# FindIt — Build Progress

${headline}

\`\`\`
${bar}
\`\`\`

Generated by \`node scripts/update-progress.mjs\` from docs/ROADMAP.md. Do not edit by hand.

## Next up
${next.join("\n")}

${open.length > next.length ? `…and ${open.length - next.length} more in docs/ROADMAP.md.\n` : ""}`;
writeFileSync("PROGRESS.md", progress);

console.log(`${done}/${total} tasks done (${percent}%)`);
