-- Lost Mode, reconnect alerts, plan limits, and billing-integrity hardening.
-- Depends on 0004_device_credentials.sql.

------------------------------------------------------------------------
-- 1. Device columns
------------------------------------------------------------------------
alter table public.devices
  add column if not exists lost_mode boolean not null default false,
  add column if not exists lost_mode_message text,
  add column if not exists lost_mode_contact text,
  add column if not exists lost_mode_enabled_at timestamptz,
  add column if not exists notify_on_reconnect boolean not null default false;

------------------------------------------------------------------------
-- 2. Alerts / audit timeline
------------------------------------------------------------------------
create table if not exists public.device_alerts (
  id bigint generated by default as identity primary key,
  device_id uuid not null references public.devices(id) on delete cascade,
  owner_id uuid not null references auth.users(id) on delete cascade,
  kind text not null check (kind in (
    'RECONNECTED', 'WENT_OFFLINE', 'LOST_MODE_ENABLED', 'LOST_MODE_DISABLED'
  )),
  message text,
  created_at timestamptz not null default now(),
  read_at timestamptz
);

create index if not exists device_alerts_owner_created_idx
  on public.device_alerts (owner_id, created_at desc);
create index if not exists device_alerts_device_created_idx
  on public.device_alerts (device_id, created_at desc);

alter table public.device_alerts enable row level security;

create policy "owners can view their alerts"
  on public.device_alerts for select
  using (auth.uid() = owner_id);

create policy "owners can mark their alerts read"
  on public.device_alerts for update
  using (auth.uid() = owner_id)
  with check (auth.uid() = owner_id);

-- Alerts are written only by the database functions below.
revoke insert, update, delete on public.device_alerts from anon, authenticated;
grant update (read_at) on public.device_alerts to authenticated;

------------------------------------------------------------------------
-- 3. Billing integrity: users must not be able to grant themselves a plan,
--    flip Lost Mode directly, or forge device state / location events.
------------------------------------------------------------------------
drop policy if exists "owners can create their subscription" on public.subscriptions;
drop policy if exists "owners can update their subscription" on public.subscriptions;
revoke insert, update, delete on public.subscriptions from anon, authenticated;

revoke insert, update on public.devices from anon, authenticated;
grant insert (id, owner_id, name, model, platform, status, enrollment_code)
  on public.devices to authenticated;
grant update (name, model, platform) on public.devices to authenticated;

drop policy if exists "owners can create their location events" on public.location_events;
revoke insert, update, delete on public.location_events from anon, authenticated;

------------------------------------------------------------------------
-- 4. Plans. This is the single source of truth for what each plan includes.
--    FREE = no active subscription (one device, last-known location only).
------------------------------------------------------------------------
create or replace function public.plan_limits(
  p_plan text,
  out max_devices integer,
  out lost_mode boolean,
  out reconnect_alerts boolean
)
language sql
immutable
as $$
  select case p_plan
           when 'FAMILY' then 10
           when 'PLUS' then 3
           else 1
         end,
         p_plan in ('PLUS', 'FAMILY'),
         p_plan in ('BASIC', 'PLUS', 'FAMILY');
$$;

create or replace function public.effective_plan(p_owner_id uuid)
returns text
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(
    (select case when s.status in ('ACTIVE', 'PAST_DUE') then s.plan else 'FREE' end
       from public.subscriptions s
      where s.owner_id = p_owner_id),
    'FREE'
  );
$$;

revoke all on function public.effective_plan(uuid) from public, anon, authenticated;
grant execute on function public.effective_plan(uuid) to service_role;

create or replace function public.my_plan_status()
returns table (
  plan text,
  subscription_status text,
  max_devices integer,
  device_count integer,
  lost_mode boolean,
  reconnect_alerts boolean
)
language sql
stable
security definer
set search_path = public
as $$
  select p.plan,
         coalesce((select s.status from public.subscriptions s where s.owner_id = auth.uid()), 'NONE'),
         l.max_devices,
         (select count(*)::integer from public.devices d where d.owner_id = auth.uid()),
         l.lost_mode,
         l.reconnect_alerts
    from (select public.effective_plan(auth.uid()) as plan) p,
         public.plan_limits(p.plan) l;
$$;

revoke all on function public.my_plan_status() from public, anon;
grant execute on function public.my_plan_status() to authenticated;

-- Enforce the device limit at insert time, regardless of client.
create or replace function public.enforce_device_limit()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_plan text;
  v_max integer;
  v_count integer;
begin
  v_plan := public.effective_plan(new.owner_id);
  select l.max_devices into v_max from public.plan_limits(v_plan) l;
  select count(*) into v_count from public.devices where owner_id = new.owner_id;

  if v_count >= v_max then
    raise exception 'DEVICE_LIMIT_REACHED: your % plan includes % device(s). Upgrade to enroll more.', v_plan, v_max;
  end if;

  return new;
end;
$$;

drop trigger if exists devices_enforce_limit on public.devices;
create trigger devices_enforce_limit
  before insert on public.devices
  for each row execute function public.enforce_device_limit();

------------------------------------------------------------------------
-- 5. Owner actions: Lost Mode and reconnect alerts
------------------------------------------------------------------------
create or replace function public.set_lost_mode(
  p_device_id uuid,
  p_enabled boolean,
  p_message text default null,
  p_contact text default null
)
returns public.devices
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_device public.devices;
  v_was_enabled boolean;
  v_allowed boolean;
  v_message text := nullif(trim(coalesce(p_message, '')), '');
  v_contact text := nullif(trim(coalesce(p_contact, '')), '');
begin
  if v_uid is null then
    raise exception 'Authentication required';
  end if;

  select * into v_device
    from public.devices
   where id = p_device_id and owner_id = v_uid
   for update;

  if not found then
    raise exception 'Device not found';
  end if;

  v_was_enabled := v_device.lost_mode;

  if p_enabled then
    select l.lost_mode into v_allowed
      from public.plan_limits(public.effective_plan(v_uid)) l;

    if not v_allowed then
      raise exception 'UPGRADE_REQUIRED: Lost Mode is included in the Plus and Family plans.';
    end if;
    if length(coalesce(v_message, '')) > 280 then
      raise exception 'The message must be 280 characters or fewer.';
    end if;
    if length(coalesce(v_contact, '')) > 120 then
      raise exception 'The contact detail must be 120 characters or fewer.';
    end if;
  end if;

  update public.devices
     set lost_mode = p_enabled,
         lost_mode_message = case when p_enabled then v_message else null end,
         lost_mode_contact = case when p_enabled then v_contact else null end,
         lost_mode_enabled_at = case
           when p_enabled and not v_was_enabled then now()
           when p_enabled then lost_mode_enabled_at
           else null
         end,
         updated_at = now()
   where id = p_device_id
   returning * into v_device;

  if p_enabled <> v_was_enabled then
    insert into public.device_alerts (device_id, owner_id, kind, message)
    values (
      v_device.id,
      v_uid,
      case when p_enabled then 'LOST_MODE_ENABLED' else 'LOST_MODE_DISABLED' end,
      case when p_enabled then 'Lost Mode turned on for ' || v_device.name
           else 'Lost Mode turned off for ' || v_device.name end
    );
  end if;

  return v_device;
end;
$$;

revoke all on function public.set_lost_mode(uuid, boolean, text, text) from public, anon;
grant execute on function public.set_lost_mode(uuid, boolean, text, text) to authenticated;

create or replace function public.set_reconnect_alerts(
  p_device_id uuid,
  p_enabled boolean
)
returns public.devices
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_device public.devices;
  v_allowed boolean;
begin
  if v_uid is null then
    raise exception 'Authentication required';
  end if;

  if p_enabled then
    select l.reconnect_alerts into v_allowed
      from public.plan_limits(public.effective_plan(v_uid)) l;

    if not v_allowed then
      raise exception 'UPGRADE_REQUIRED: Reconnect alerts are included in every paid plan.';
    end if;
  end if;

  update public.devices
     set notify_on_reconnect = p_enabled,
         updated_at = now()
   where id = p_device_id and owner_id = v_uid
   returning * into v_device;

  if not found then
    raise exception 'Device not found';
  end if;

  return v_device;
end;
$$;

revoke all on function public.set_reconnect_alerts(uuid, boolean) from public, anon;
grant execute on function public.set_reconnect_alerts(uuid, boolean) to authenticated;

------------------------------------------------------------------------
-- 6. Ingestion: reconnect detection and Lost Mode instructions for the companion.
--    Ingestion is never plan-gated, so a lapsed subscription cannot cut off recovery.
------------------------------------------------------------------------
drop function if exists public.ingest_device_location(
  uuid, text, double precision, double precision, double precision, integer, timestamptz
);

create or replace function public.ingest_device_location(
  p_device_id uuid,
  p_token_hash text,
  p_latitude double precision,
  p_longitude double precision,
  p_accuracy_m double precision default null,
  p_battery_pct integer default null,
  p_recorded_at timestamptz default now()
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_device public.devices;
  v_credential public.device_credentials;
  v_event public.location_events;
  v_reconnected boolean;
begin
  if p_latitude < -90 or p_latitude > 90 or p_longitude < -180 or p_longitude > 180 then
    raise exception 'Invalid coordinates';
  end if;

  if p_accuracy_m is not null and p_accuracy_m < 0 then
    raise exception 'Invalid accuracy';
  end if;

  if p_battery_pct is not null and (p_battery_pct < 0 or p_battery_pct > 100) then
    raise exception 'Invalid battery percentage';
  end if;

  select * into v_credential
    from public.device_credentials
   where device_id = p_device_id
     and token_hash = p_token_hash
     and revoked_at is null;

  if not found then
    raise exception 'Invalid device credential';
  end if;

  select * into v_device
    from public.devices
   where id = p_device_id
   for update;

  if not found then
    raise exception 'Invalid device credential';
  end if;

  v_reconnected := v_device.status <> 'ONLINE';

  insert into public.location_events (
    device_id, owner_id, latitude, longitude, accuracy_m, battery_pct, recorded_at
  )
  values (
    v_device.id, v_device.owner_id, p_latitude, p_longitude,
    p_accuracy_m, p_battery_pct, coalesce(p_recorded_at, now())
  )
  returning * into v_event;

  update public.devices
     set status = 'ONLINE',
         battery_pct = p_battery_pct,
         last_seen_at = coalesce(p_recorded_at, now()),
         last_latitude = p_latitude,
         last_longitude = p_longitude,
         last_location_accuracy_m = p_accuracy_m,
         -- "Alert me when online" is one-shot; Lost Mode always alerts.
         notify_on_reconnect = case when v_reconnected then false else notify_on_reconnect end,
         updated_at = now()
   where id = v_device.id;

  if v_reconnected and (v_device.notify_on_reconnect or v_device.lost_mode) then
    insert into public.device_alerts (device_id, owner_id, kind, message)
    values (
      v_device.id,
      v_device.owner_id,
      'RECONNECTED',
      v_device.name || ' is back online and reported a fresh location.'
    );
  end if;

  update public.device_credentials
     set last_used_at = now()
   where id = v_credential.id;

  return jsonb_build_object(
    'event_id', v_event.id,
    'lost_mode', v_device.lost_mode,
    'lost_message', v_device.lost_mode_message,
    'lost_contact', v_device.lost_mode_contact,
    -- Hint for the authorized companion: report more often while the owner is searching.
    'report_interval_s', case when v_device.lost_mode then 60 else 900 end
  );
end;
$$;

revoke all on function public.ingest_device_location(
  uuid, text, double precision, double precision, double precision, integer, timestamptz
) from public, anon, authenticated;

grant execute on function public.ingest_device_location(
  uuid, text, double precision, double precision, double precision, integer, timestamptz
) to service_role;

------------------------------------------------------------------------
-- 7. Heartbeat sweep: mark silent devices OFFLINE. Run on a schedule via
--    /api/cron/mark-offline. Only Lost Mode devices raise an alert.
------------------------------------------------------------------------
create or replace function public.mark_stale_devices_offline(
  p_stale_after interval default interval '30 minutes'
)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_count integer;
begin
  with stale as (
    update public.devices
       set status = 'OFFLINE',
           updated_at = now()
     where status = 'ONLINE'
       and last_seen_at is not null
       and last_seen_at < now() - p_stale_after
     returning id, owner_id, name, lost_mode
  ),
  alerts as (
    insert into public.device_alerts (device_id, owner_id, kind, message)
    select id, owner_id, 'WENT_OFFLINE', name || ' went offline. Showing its last known location.'
      from stale
     where lost_mode
    returning 1
  )
  select count(*)::integer into v_count from stale;

  return v_count;
end;
$$;

revoke all on function public.mark_stale_devices_offline(interval) from public, anon, authenticated;
grant execute on function public.mark_stale_devices_offline(interval) to service_role;
